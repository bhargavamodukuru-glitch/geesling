// Geesling covers Toronto only. Pure and import-free so it can be unit-tested under plain Node.

/** A box around the City of Toronto with a small margin (Steeles Ave to the lake, Etobicoke to the Rouge). */
export const TORONTO_BOUNDS = { south: 43.55, north: 43.9, west: -79.67, east: -79.09 };

export const TORONTO_SPAN = {
  lat: TORONTO_BOUNDS.north - TORONTO_BOUNDS.south,
  lng: TORONTO_BOUNDS.east - TORONTO_BOUNDS.west,
};

/** How far past the city limit people may pan before the map stops, so the border and the area outside it stay visible. */
export const PAN_MARGIN = { lat: 0.2, lng: 0.3 };
export const PAN_BOUNDS = {
  south: TORONTO_BOUNDS.south - PAN_MARGIN.lat,
  north: TORONTO_BOUNDS.north + PAN_MARGIN.lat,
  west: TORONTO_BOUNDS.west - PAN_MARGIN.lng,
  east: TORONTO_BOUNDS.east + PAN_MARGIN.lng,
};

/** Ray casting against the real city limit; the box is only a quick first check. */
export function isInToronto(lat: number, lng: number): boolean {
  if (lat < TORONTO_BOUNDS.south || lat > TORONTO_BOUNDS.north || lng < TORONTO_BOUNDS.west || lng > TORONTO_BOUNDS.east) return false;
  let inside = false;
  for (let i = 0, j = TORONTO_RING.length - 1; i < TORONTO_RING.length; j = i++) {
    const [latI, lngI] = TORONTO_RING[i];
    const [latJ, lngJ] = TORONTO_RING[j];
    if (latI > lat !== latJ > lat && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI) inside = !inside;
  }
  return inside;
}

/** Whether the middle of what the map is showing is inside the city. */
export function isViewInToronto(b: { minLat: number; maxLat: number; minLng: number; maxLng: number }): boolean {
  return isInToronto((b.minLat + b.maxLat) / 2, (b.minLng + b.maxLng) / 2);
}

// Places people commonly ask about that are not Toronto. Only checked when the message never says "Toronto".
const OTHER_PLACES =
  /\b(mississauga|brampton|vaughan|markham|richmond hill|oakville|burlington|hamilton|pickering|ajax|oshawa|whitby|milton|niagara|ottawa|montreal|montréal|vancouver|calgary|new york|nyc|london|paris|chicago|boston|los angeles|kingston|barrie|waterloo|kitchener|guelph|windsor|muskoka|prince edward county)\b/i;

/** True when the request is clearly about somewhere else. Misses are caught by the guide's own rules. */
export function mentionsOtherPlace(text: string): boolean {
  return !/\b(toronto|gta)\b/i.test(text) && OTHER_PLACES.test(text);
}

export const OUT_OF_AREA_MESSAGE = "Honk! Development in progress for this area. For now I only know my way around Toronto.";

/** The nearest point inside the pan area; a point already inside comes back unchanged. */
export function clampToPanArea(lat: number, lng: number): { lat: number; lng: number } {
  return {
    lat: Math.min(PAN_BOUNDS.north, Math.max(PAN_BOUNDS.south, lat)),
    lng: Math.min(PAN_BOUNDS.east, Math.max(PAN_BOUNDS.west, lng)),
  };
}

